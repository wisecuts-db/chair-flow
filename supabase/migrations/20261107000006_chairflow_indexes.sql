create index if not exists sales_appointment_idx        on sales (appointment_id);
create index if not exists sales_client_idx             on sales (client_id);
create index if not exists walkins_assigned_idx         on walkins (assigned_to, joined_at desc);
create index if not exists walkins_preferred_idx        on walkins (preferred_barber);
create index if not exists walkins_service_idx          on walkins (service_id);
create index if not exists rent_charges_renter_idx      on rent_charges (renter_id, due_on desc);
create index if not exists rent_charges_contract_idx    on rent_charges (contract_id);
create index if not exists rent_payments_charge_idx     on rent_payments (charge_id);
create index if not exists contracts_renter_idx         on contracts (renter_id);
create index if not exists contracts_location_idx       on contracts (location_id, status);
create index if not exists contracts_chair_idx          on contracts (chair_id);
create index if not exists contracts_supersedes_idx     on contracts (supersedes);
create index if not exists contracts_template_idx       on contracts (template_id);
create index if not exists appointments_client_idx      on appointments (client_id);
create index if not exists appointments_service_idx     on appointments (service_id);
create index if not exists availability_membership_idx  on availability (membership_id);
create index if not exists time_off_membership_idx      on time_off (membership_id);
create index if not exists staff_documents_member_idx   on staff_documents (membership_id);
create index if not exists services_location_idx        on services (location_id);
create index if not exists services_renter_idx          on services (renter_id);
create index if not exists clients_renter_idx           on clients (renter_id);
create index if not exists clients_pref_barber_idx      on clients (preferred_barber);
create index if not exists clients_pref_location_idx    on clients (preferred_location);
create index if not exists clients_phone_idx            on clients (business_id, phone);
create index if not exists businesses_owner_idx         on businesses (owner_id);
create index if not exists locations_business_idx       on locations (business_id);
create index if not exists memberships_chair_idx        on memberships (chair_id);
create index if not exists memberships_manager_idx      on memberships (manager_id);
create index if not exists contract_templates_biz_idx   on contract_templates (business_id);
